function Show-Shortcuts {
    Write-Host "`n=== Shortcut PowerShell / Windows Terminal ===" -ForegroundColor Cyan
    Write-Host "New tab        : Ctrl + Shift + T"
    Write-Host "Close tab      : Ctrl + Shift + W"
    Write-Host "Next / Prev tab: Ctrl + Tab / Ctrl + Shift + Tab"
    Write-Host "Settings       : Ctrl + ,"
    Write-Host "Command palette: Ctrl + Shift + ,"
}
